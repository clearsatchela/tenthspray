#include <string>
#include <vector>

void digit_count() {
    int n = 1234567;
    int digits = 0;
    while (n > 0) { digits += 1; n /= 10; }
    (void)digits;
}

void shift_right() {
    unsigned int n = 256u;
    unsigned int shifted = n >> 3;
    (void)shifted;
}

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

void swap_values() {
    int a = 5, b = 11;
    int tmp = a;
    a = b;
    b = tmp;
    (void)a;
    (void)b;
}

void geometric_sum() {
    int acc = 0;
    int term = 1;
    for (int i = 0; i < 8; ++i) { acc += term; term *= 2; }
    (void)acc;
}

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

extern "C" int silver_thorn();
extern "C" void placid_willow();
extern "C" void frost_fjord();

int main() {
    digit_count();
    shift_right();
    is_prime();
    swap_values();
    geometric_sum();
    least_multiple();
    placid_willow();
    frost_fjord();
    return silver_thorn();
}
